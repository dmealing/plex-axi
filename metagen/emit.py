class CaptureContract:
    name = "metagen-capture-contract"

    def generate(self, ctx):
        root = ctx.loaded_root
        objects, rows = model.upstream(root), model.rows(root)
        declared = {
            entry.fqn: {
                "key": entry.key,
                "capture": entry.capture,
                "fields": entry.fields,
                "unobserved": entry.unobserved,
            }
            for entry in objects
        }
        reads = {
            row.key: {
                "of": row.of,
                "capture": row.capture,
                "reads": tuple(sorted({name for names in row.reads.values() for name in names})),
            }
            for row in rows
        }
        contract = (
            _header("capture_contract")
            + '"""What the model declares, held to a committed capture of a real server.\n'
            "\n"
            "It fails in one direction: an attribute that is declared, is in no captured\n"
            "answer, and carries no reason it could not be observed. That is an invented\n"
            "name, and whatever reads it is empty on every real server. The other direction\n"
            "is reported and never failed: a server sends far more than a tool reads, and\n"
            "the model declares what is read.\n"
            "\n"
            "Run this file to print both directions. The standard library is all it needs.\n"
            '"""\n'
            "\n"
            "from __future__ import annotations\n"
            "\n"
            "import json\n"
            "import sys\n"
            "from pathlib import Path\n"
            "\n"
            "#: The committed capture, as a path from the project root.\n"
            f"CAPTURE_FILE = {_string(model.capture_file(root))}\n"
            "\n"
            "#: Each declared object: the captured answers that show it, its attributes, and\n"
            "#: the reason for any that no capture could have seen.\n"
            + _assign("DECLARED", declared)
            + "\n"
            "#: Each row: the object it is read from, the answers it is built from, and the\n"
            "#: attributes it reads.\n" + _assign("ROWS", reads) + _CONTRACT
        )
        test = (
            _header("capture_contract")
            + '"""The capture check, as tests: see ``capture_contract`` beside this file."""\n'
            + _CONTRACT_TEST
        )
        return [
            EmittedFile(path="capture_contract.py", content=contract),
            EmittedFile(path="test_capture_contract.py", content=test),
        ]


rows, elements, capture_contract = Rows(), Elements(), CaptureContract()
